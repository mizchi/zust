//! Copies `Vec<T>` from zustc's prelude (crates/syntax/src/prelude_lib.rs.in) into `$OUT_DIR/vec.rs`, so the
//! harnesses check the code zustc compiles, not a copy of it. Only the listed methods are taken (the rest of the
//! prelude needs zustc's own intrinsics); the build fails if one of them is not found.

use std::fmt::Write;

const PRELUDE: &str = "../../crates/syntax/src/prelude_lib.rs.in";
const METHODS: &[&str] = &[
    "new", "with_capacity", "reserve", "push", "pop", "len", "is_empty", "capacity", "truncate", "clear", "get",
    "insert", "remove", "swap_remove", "swap", "reverse",
];

/// The text from `start` to its matching `}` (the first `{` after start opens it)
fn braced(src: &str, start: usize) -> &str {
    let open = start + src[start..].find('{').expect("no `{`");
    let mut depth = 0;
    for (i, c) in src[open..].char_indices() {
        match c {
            '{' => depth += 1,
            '}' => {
                depth -= 1;
                if depth == 0 {
                    return &src[start..open + i + 1];
                }
            }
            _ => {}
        }
    }
    panic!("unbalanced braces")
}

fn main() {
    println!("cargo:rerun-if-changed={PRELUDE}");
    let src = std::fs::read_to_string(PRELUDE).expect(PRELUDE);
    let st = src.find("pub struct Vec<T> {").expect("struct Vec");
    let block = braced(&src, src[st..].find("impl<T> Vec<T> {").expect("impl Vec") + st);
    let mut out = String::new();
    writeln!(out, "// generated by build.rs from {PRELUDE}").unwrap();
    writeln!(out, "{}\n", braced(&src, st)).unwrap();
    writeln!(out, "impl<T> Vec<T> {{").unwrap();
    for m in METHODS {
        let pat = format!("    pub fn {m}(");
        let at = block.find(&pat).unwrap_or_else(|| panic!("Vec::{m} not found in the prelude"));
        writeln!(out, "{}\n", braced(block, at)).unwrap();
    }
    writeln!(out, "}}\n").unwrap();
    let d = src.find("impl<T> Drop for Vec<T> {").expect("Drop for Vec");
    writeln!(out, "{}", braced(&src, d)).unwrap();
    std::fs::write(std::path::Path::new(&std::env::var("OUT_DIR").unwrap()).join("vec.rs"), out).unwrap();
}
