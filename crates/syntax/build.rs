//! Does the item splitting of the prelude (src/prelude_lib.rs.in) at build time.
//! Because splitting the whole prelude (thousands of lines) with the lexer on every run takes half the build time of a small program.
//! The splitting uses src/lexer.rs and zust-base's key.rs as they are: each item's hash is the one lexer::split gives
//! it in the selected prelude text (its tokens', and its impl's header's for a member), so the selection's items need
//! not be split again (prelude::select_with).

use std::fmt::Write;

#[path = "src/lexer.rs"]
#[allow(dead_code)]
mod lexer;

#[path = "../base/src/key.rs"]
#[allow(dead_code)]
mod key;

fn main() {
    println!("cargo:rerun-if-changed=src/prelude_lib.rs.in");
    println!("cargo:rerun-if-changed=src/lexer.rs");
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=../base/src/key.rs");
    let src = std::fs::read_to_string("src/prelude_lib.rs.in").unwrap();
    let items = lexer::split(&src).expect("prelude must lex");
    let mut out = String::new();
    out.push_str("// generated by build.rs: the prelude's items (start, end, line, kind, kind's argument, identifiers, the hash's high and low halves,\n");
    out.push_str("// the name it defines (lexer::prelude_item_name), whether it is usable only through core:: (an identifier `__core_..`))\n");
    out.push_str("pub static PRELUDE_ITEMS: &[(u32, u32, u32, u8, u32, &[(u32, u32)], u64, u64, Option<&str>, bool)] = &[\n");
    for it in &items {
        let (k, a) = match it.kind {
            lexer::ItemKind::Normal => (0, 0),
            lexer::ItemKind::ImplHeader => (1, 0),
            lexer::ItemKind::ImplMember(h) => (2, h),
            lexer::ItemKind::TraitHeader => (3, 0),
            lexer::ItemKind::TraitMember(h) => (4, h),
            lexer::ItemKind::InnerAttr => (5, 0),
        };
        write!(out, "({}, {}, {}, {k}, {a}, &[", it.start, it.end, it.line).unwrap();
        for (x, y) in &it.idents {
            write!(out, "({x}, {y}),").unwrap();
        }
        let header = match it.kind {
            lexer::ItemKind::ImplMember(h) => Some(&items[h as usize].idents[..]),
            _ => None,
        };
        let name = lexer::prelude_item_name(&src, &it.idents, matches!(it.kind, lexer::ItemKind::Normal), header);
        let core_only = it.idents.iter().any(|&(a, b)| src[a as usize..b as usize].starts_with("__core_"));
        // (two u64s, not a u128 literal: the self-host compiles this table too)
        write!(out, "], {}, {}, {name:?}, {core_only}),\n", (it.hash >> 64) as u64, it.hash as u64).unwrap();
    }
    out.push_str("];\n");
    // (the names the prelude gives a struct / enum / trait / union: prelude::rename_user_collisions)
    out.push_str("pub static PRELUDE_TYPE_NAMES: &[&str] = &[\n");
    for it in &items {
        if !matches!(it.kind, lexer::ItemKind::Normal | lexer::ItemKind::TraitHeader) {
            continue;
        }
        let mut ids = it.idents.iter().take(6).map(|&(a, b)| &src[a as usize..b as usize]);
        if ids.any(|w| matches!(w, "struct" | "enum" | "trait" | "union")) {
            if let Some(n) = ids.next() {
                write!(out, "{n:?},").unwrap();
            }
        }
    }
    out.push_str("];\n");
    let dst = std::path::Path::new(&std::env::var("OUT_DIR").unwrap()).join("prelude_items.rs");
    std::fs::write(dst, out).unwrap();
}
