//! zsc for the browser: the front end of crates/zustscript (its modules, included as they are), with every
//! `@wasm` / `@simd` fn kept in the JS output (`--all-js`: zustc does not run here) and the runtime written into
//! the module (`--inline-runtime`).
//!
//! The ABI is raw: `zsc_alloc(n)` gives a buffer for the UTF-8 source, `zsc_compile(ptr, n)` compiles it and
//! returns the length of a JSON result `{ok, js, dts, diagnostics: [{severity, line, col, message}]}` that
//! `zsc_result()` points at (valid until the next call).

