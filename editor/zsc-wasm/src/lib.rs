use std::cell::RefCell;
use std::path::Path;

thread_local! {
    static RESULT: RefCell<Vec<u8>> = const { RefCell::new(Vec::new()) };
}

#[unsafe(no_mangle)]
pub extern "C" fn zsc_alloc(n: usize) -> *mut u8 {
    let mut v = Vec::<u8>::with_capacity(n.max(1));
    let p = v.as_mut_ptr();
    std::mem::forget(v);
    p
}

#[unsafe(no_mangle)]
pub extern "C" fn zsc_free(p: *mut u8, n: usize) {
    unsafe { drop(Vec::from_raw_parts(p, 0, n.max(1))) }
}

#[unsafe(no_mangle)]
pub extern "C" fn zsc_result() -> *const u8 {
    RESULT.with(|r| r.borrow().as_ptr())
}

#[unsafe(no_mangle)]
pub extern "C" fn zsc_compile(p: *const u8, n: usize) -> usize {
    let bytes = unsafe { std::slice::from_raw_parts(p, n) };
    let src = String::from_utf8_lossy(bytes).to_string();
    let json = match compile(&src) {
        Ok((js, dts, warns)) => format!(r#"{{"ok":true,"js":{},"dts":{},"diagnostics":{}}}"#, q(&js), q(&dts), diags("warning", &warns)),
        Err(errs) => format!(r#"{{"ok":false,"js":"","dts":"","diagnostics":{}}}"#, diags("error", &errs)),
    };
    RESULT.with(|r| {
        *r.borrow_mut() = json.into_bytes();
        r.borrow().len()
    })
}

type Diag = (ast::Pos, String);

fn sorted(mut v: Vec<Diag>) -> Vec<Diag> {
    v.sort_by_key(|e| (e.0.line, e.0.col));
    v.dedup();
    v
}

/// The pipeline of `zsc --all-js --inline-runtime` (src/main.rs), without the files
fn compile(src: &str) -> Result<(String, String, Vec<Diag>), Vec<Diag>> {
    let items = parse::Parser::new(src).file().map_err(|e| vec![e])?;
    let items = tsimport::expand(items, Path::new(".")).map_err(|errs| {
        errs.into_iter()
            .map(|e| (e.pos, if e.file.is_some() { e.msg } else { format!("{} (the playground has no TS files to import)", e.msg) }))
            .collect::<Vec<_>>()
    })?;
    let mut ck = check::Checker::new();
    ck.check_file(&items);
    if !ck.errors.is_empty() {
        return Err(sorted(ck.errors.clone()));
    }
    let mut warns = ck.warnings.clone();
    // `wasm fn`s / `wasm { .. }` are Rust for zustc, which does not run here: calling one throws
    let mut stubs = String::new();
    for it in &items {
        if let ast::Item::WasmFn { name, public, pos, .. } = it {
            warns.push((*pos, format!("`{name}` is Rust (a `wasm fn`): zustc does not run in the browser, so calling it throws here (an `@wasm fn` runs as JS)")));
            let msg = q(&format!("`{name}` is a Rust `wasm fn`: the playground cannot compile it (zustc does not run in the browser)"));
            stubs.push_str(&format!("\n{}function {}() {{\n  throw new Error({msg});\n}}\n", if *public { "export " } else { "" }, js::ident(name)));
        }
    }
    let warns = sorted(warns);
    let info = ck.info;
    let mut j = js::Js::new(&info, "react/jsx-runtime");
    j.shared_runtime = false;
    let body = j.items(&items);
    if !j.errors.is_empty() {
        return Err(sorted(j.errors.clone()));
    }
    let header = j.header();
    let (dts, brands) = js::dts(&items, &info, false, &|ts| tsimport::specifier(Path::new("."), ts));
    let mut out = String::from("// generated by zsc (playground: @wasm fns run as JS)\n");
    out.push_str(&header);
    out.push_str(&body);
    out.push_str(&stubs);
    out.push_str(&js::brand_runtime(&brands));
    Ok((out, dts, warns))
}

fn q(s: &str) -> String {
    let mut o = String::with_capacity(s.len() + 2);
    o.push('"');
    for c in s.chars() {
        match c {
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            '\n' => o.push_str("\\n"),
            '\r' => o.push_str("\\r"),
            '\t' => o.push_str("\\t"),
            c if (c as u32) < 0x20 || c == '\u{2028}' || c == '\u{2029}' => o.push_str(&format!("\\u{:04x}", c as u32)),
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

fn diags(sev: &str, ds: &[Diag]) -> String {
    let v: Vec<String> = ds
        .iter()
        .map(|(p, m)| format!(r#"{{"severity":"{sev}","line":{},"col":{},"message":{}}}"#, p.line, p.col, q(m)))
        .collect();
    format!("[{}]", v.join(","))
}
